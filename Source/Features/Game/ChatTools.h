// --- fake kick (networked "Invalid Steam Logon" / reason kick) -------------------------
//
// The engine interface Source2EngineToClient001::CmdKeyValues (vtable byte offset 0x3B8 =
// slot 119) forwards a KeyValues message to the server; sending KV name "InvalidSteamLogon"
// with an int "reason" makes the SERVER kick us with that reason ("Invalid Steam Logon
// Delayed: Kicking client [U:1:%d] %s" in the server log) - a REAL disconnect line every
// player sees. Ported from a friend's Windows PoC; every KeyValues method is dlsym-able from
// libtier0 by mangled name (update-proof, no RVAs), the interface comes from engine2's
// exported CreateInterface. The Linux vtable slot was confirmed identical to Windows
// (multiple `call *0x3b8` sites through the engine global at libclient+0x4821138, the
// game's own CrosshairCode sender at +0x14fcd20 uses the same construction sequence).
//
// The burst (one send per frame for ~180 frames) exists because the server only stores the
// delayed-kick reason in a specific client-state window. Dispatch must run on the game
// thread (the net channel/KV path is not thread-safe) - our run() already is.
//
// OWNERSHIP: the engine takes the KV (the game's own sender does NOT free after dispatch) -
// do NOT delete after sending.
inline void* engineInterface = nullptr;
inline bool kickSymbolsResolved = false;

using KVNewFn = void* (*)(std::size_t);
using KVCtorFn = void* (*)(void*, const char*, void*, bool);
using KVSetIntFn = void (*)(void*, const char*, int);
using CreateInterfaceFn = void* (*)(const char*, int*);
using DispatchFn = void (*)(void*, void*);

inline KVNewFn kvNew = nullptr;
inline KVCtorFn kvCtor = nullptr;
inline KVSetIntFn kvSetInt = nullptr;
inline DispatchFn cmdKeyValues = nullptr;

inline bool resolveKickSymbols() noexcept
{
    if (kickSymbolsResolved)
        return engineInterface && cmdKeyValues;

    kickSymbolsResolved = true;
    DynamicLibrary tier0{cs2::TIER0_DLL};
    kvNew = tier0.getFunctionAddress("_ZN9KeyValuesnwEm").as<KVNewFn>();
    kvCtor = tier0.getFunctionAddress("_ZN9KeyValuesC1EPKcP16IKeyValuesSystemb").as<KVCtorFn>();
    kvSetInt = tier0.getFunctionAddress("_ZN9KeyValues6SetIntEPKci").as<KVSetIntFn>();
    if (!kvNew || !kvCtor || !kvSetInt)
        return false;

    DynamicLibrary engine2{cs2::ENGINE_DLL};
    const auto createInterface = engine2.getFunctionAddress("CreateInterface").as<CreateInterfaceFn>();
    if (!createInterface)
        return false;
    engineInterface = createInterface("Source2EngineToClient001", nullptr);
    if (!engineInterface)
        return false;

    const auto vtable = *reinterpret_cast<void***>(engineInterface);
    cmdKeyValues = reinterpret_cast<DispatchFn>(vtable[0x3B8 / 8]);
    return cmdKeyValues != nullptr;
}

// One send attempt; silent no-op while the symbols/interface are unavailable.
inline void sendInvalidSteamLogon(int reason) noexcept
{
    if (!resolveKickSymbols())
        return;
    void* kv = kvNew(0x1C);
    if (kv)
        kvCtor(kv, "InvalidSteamLogon", nullptr, false);
    kvSetInt(kv, "reason", reason);
    cmdKeyValues(engineInterface, kv);
    // the engine owns the KV (the game's own CrosshairCode sender never frees) - no delete
}

