// Strips every byte that could break out of a console command: quotes, semicolons, control
// bytes. ALSO converts the {nl} and "\n" escapes into U+2028 (Unicode LINE SEPARATOR): the
// Panorama chat renders it as a real line break while it is NOT a control byte - so it passes
// through the console parser AND the server's name/message validation untouched. This is what
// makes the multi-line persona names work networked (fake system-message blocks in chat).
inline std::size_t sanitizeInto(const char* in, char* out, std::size_t outCapacity) noexcept
{
    constexpr char kLineSeparator[] = "\xE2\x80\xA8"; // U+2028
    std::size_t writeIndex = 0;
    for (std::size_t i = 0; in[i] != '\0' && writeIndex + 4 < outCapacity; ++i) {
        const auto c = in[i];
        if (c == '{' && std::strncmp(in + i, "{nl}", 4) == 0) {
            std::memcpy(out + writeIndex, kLineSeparator, 3);
            writeIndex += 3;
            i += 3;
            continue;
        }
        if (c == '\\' && in[i + 1] == 'n') {
            std::memcpy(out + writeIndex, kLineSeparator, 3);
            writeIndex += 3;
            ++i;
            continue;
        }
        if (c == '"' || c == ';' || static_cast<unsigned char>(c) < 0x20 || c == 0x7F)
            continue;
        out[writeIndex++] = c;
    }
    out[writeIndex] = '\0';
    return writeIndex;
}

// Case-insensitive ASCII compare (the wheel/CW name resolution needs it).
[[nodiscard]] inline bool equalsIgnoreCase(const char* a, const char* b) noexcept
{
    for (int i = 0; a[i] != '\0' || b[i] != '\0'; ++i) {
        char ca = a[i];
        char cb = b[i];
        if (ca >= 'A' && ca <= 'Z')
            ca += 32;
        if (cb >= 'A' && cb <= 'Z')
            cb += 32;
        if (ca != cb)
            return false;
        if (ca == '\0')
            return true;
    }
    return true;
}

