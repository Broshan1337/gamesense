import os, re, struct, sys

# Generates cs2/Source/Features/Combat/Aimbot/RageWeaponDefs.h - the per-weapon
# rage config list (tags + item definition indices + menu names), extracted from
# the game's own items_game.txt (weapon item entries, def index = the item key)
# joined against csgo_english.txt for pretty names.
#
# Regenerate: python3 scratchpad/gen_rage_weapons.py
# (pulls a fresh items_game.txt/csgo_english.txt from the installed depot first)

VPK = "/mnt/HDD2/SteamLibrary/steamapps/common/Counter-Strike Global Offensive/game/csgo/pak01_dir.vpk"
GAME = "/mnt/HDD2/SteamLibrary/steamapps/common/Counter-Strike Global Offensive/game/csgo"
IG = '/tmp/opencode/items_game.txt'
EN = '/tmp/opencode/csgo_english.txt'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..',
                    'cs2', 'Source', 'Features', 'Combat', 'Aimbot', 'RageWeaponDefs.h')

# ---- VPK extraction (same reader as scratchpad/vpk.py) ----
def read_cstr(f):
    b = bytearray()
    while True:
        c = f.read(1)
        if not c or c == b"\0":
            return b.decode("latin1")
        b += c

def find_in_vpk(wanted):
    with open(VPK, "rb") as f:
        f.seek(0)
        sig, ver, treesize = struct.unpack("<III", f.read(12))
        assert sig == 0x55AA1234, hex(sig)
        base = 28 + treesize
        f.seek(28)
        end = 28 + treesize
        while f.tell() < end:
            ext = read_cstr(f)
            if not ext:
                break
            while True:
                path = read_cstr(f)
                if not path:
                    break
                while True:
                    name = read_cstr(f)
                    if not name:
                        break
                    crc, preload, idx, off, length, term = struct.unpack("<IHHIIH", f.read(18))
                    f.read(preload)
                    full = (path + "/" if path else "") + name + ("." + ext if ext else "")
                    if full.endswith(wanted):
                        if idx == 0x7FFF:
                            f.seek(base + off)
                            return f.read(length)
                        with open(os.path.join(GAME, "pak01_%03d.vpk" % idx), "rb") as g:
                            g.seek(off)
                            return g.read(length)
    return None

for name, path in (("items_game.txt", "scripts/items/items_game.txt"),
                   ("csgo_english.txt", "resource/csgo_english.txt")):
    if not os.path.exists(path.replace("resource/", "/tmp/opencode/").split("/")[-1]) or not os.path.exists(IG) or not os.path.exists(EN):
        data = find_in_vpk(path)
        assert data is not None, "VPK miss " + path
        os.makedirs("/tmp/opencode", exist_ok=True)
        open("/tmp/opencode/" + os.path.basename(path), "wb").write(data)
        print("extracted", path)

d = open(IG, encoding='utf-8', errors='replace').read()
t = open(EN, 'rb').read().decode('utf-8-sig', errors='replace')

def loc(tok):
    m = re.search('"%s"[ \t]+"([^"]*)"' % re.escape(tok), t)
    if not m:
        m = re.search('"%s"[ \t]+"([^"]*)"' % re.escape(tok), t, re.I)
    return m.group(1) if m else None

# The gun set (velocity weapon groups; no knives/grenades/C4/taser - the ragebot
# stands down for non-gun weapon types anyway).
GUN_FAMILIES = {
    'pistols':  ['deagle', 'elite', 'fiveseven', 'glock', 'hkp2000', 'p250',
                 'tec9', 'cz75a', 'revolver'],
    'smgs':     ['mac10', 'mp7', 'mp9', 'p90', 'ump45', 'mp5sd'],
    'rifles':   ['galilar', 'famas', 'ak47', 'm4a1', 'm4a1_silencer', 'aug', 'sg556'],
    'shotguns': ['nova', 'xm1014', 'mag7', 'sawedoff'],
    'snipers':  ['ssg08', 'awp', 'scar20', 'g3sg1'],
    'lmgs':     ['m249', 'negev'],
}

def tag_of(name):
    # weapon_m4a1_silencer -> M4a1Silencer
    return ''.join(p.capitalize() for p in name.split('_'))

weapons = []
seen_defs = set()
for family, names in GUN_FAMILIES.items():
    for n in names:
        wn = 'weapon_' + n
        m = re.search(r'"(\d{1,5})"\s*\r?\n\s*\{[^{}]*?"name"\s+"%s"' % re.escape(wn), d)
        if not m:
            sys.exit("MISSING ITEM " + wn)
        defidx = int(m.group(1))
        assert defidx not in seen_defs, "dup def " + wn
        seen_defs.add(defidx)
        pf = d.find('"%s_prefab"' % wn)
        seg = d[pf:pf + 2000] if pf >= 0 else ''
        tok = re.search(r'"item_name"\s+"([^"]+)"', seg)
        pretty = loc(tok.group(1)[1:]) if tok else None
        if not pretty:
            sys.exit("MISSING NAME " + wn)
        weapons.append((tag_of(n), defidx, pretty))

# sanity anchors - known-stable def indices
anchor = {9: 'Awp', 7: 'Ak47', 40: 'Ssg08'}
for defidx, tag in anchor.items():
    got = [w for w in weapons if w[1] == defidx]
    assert got and got[0][0] == tag, ("def index drift", defidx, got)

lines = []
lines.append('// GENERATED by scratchpad/gen_rage_weapons.py - DO NOT EDIT BY HAND.')
lines.append('// Source of truth: the game\'s own scripts/items/items_game.txt (weapon item')
lines.append('// entries, item key = item definition index) joined against csgo_english.txt.')
lines.append('// Regen after a game update: python3 scratchpad/gen_rage_weapons.py')
lines.append('#pragma once')
lines.append('')
lines.append('// Per-weapon rage config entries (tags + def indices + menu names). The tags')
lines.append('// are additional "groups" for the template-alias config model in')
lines.append('// RageGroupsConfigVariables.h - every alias applies to them unchanged. The')
lines.append('// gameplay resolution (RageGroups.h active()) prefers the weapon\'s own config')
lines.append('// when its OverrideEnabled is set, else falls back to the weapon-type group.')
lines.append('namespace rage_groups {')
lines.append('')
for tag, defidx, pretty in weapons:
    lines.append('struct %s {};' % tag)
lines.append('')
lines.append('} // namespace rage_groups')
lines.append('')
lines.append('// One entry per configurable gun. X(Tag, itemDefinitionIndex, menuName).')
lines.append('// Two list forms: _LIST separates invocations with commas (expression contexts,')
lines.append('// e.g. TypeList arguments, array initializers); _LIST_NS has no separators')
lines.append('// (statement contexts, e.g. switch cases - each X emits whole statements).')
lines.append('// Order is fixed (config files are order-sensitive): pistols, smgs, rifles,')
lines.append('// shotguns, snipers, lmgs - the same order as the weapon groups, weapons after.')
rows = ['    X(%s, %d, "%s")' % (tag, defidx, pretty) for tag, defidx, pretty in weapons]
lines.append('#define RAGE_WEAPON_CONFIG_LIST(X) \\')
lines.append(' \\\n'.join(r + (',' if i < len(rows) - 1 else '') for i, r in enumerate(rows)))
lines.append('')
lines.append('#define RAGE_WEAPON_CONFIG_LIST_NS(X) \\')
lines.append(' \\\n'.join(rows))
lines.append('')
lines.append('namespace rage_weapons {')
lines.append('constexpr int kCount = %d;' % len(weapons))
lines.append('struct WeaponDef { const char* name; int defIndex; };')
lines.append('constexpr WeaponDef kDefs[kCount] = {')
lines.append(',\n'.join('    {"%s", %d}' % (pretty, defidx) for _, defidx, pretty in weapons))
lines.append('};')
lines.append('}')

hdr = '\n'.join(lines) + '\n'
open(OUT, 'w').write(hdr)
print('wrote', OUT, len(weapons), 'weapons')