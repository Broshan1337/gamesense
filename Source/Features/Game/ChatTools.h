    // Menu (present thread) buffer access - DiscordRpc buffer pattern. The lazy sidecar load
    // happens on the game thread (ensureBuffersLoaded); until then the menu may show an empty
    // field for one frame, harmless.
    static char* buffer(int kind) noexcept
    {
        return chat_tools::buffers[kind].text;
    }

    // Flushes a buffer to its sidecar. Call through ui_config::withContext so the config dir
    // is resolvable (present-thread file IO, same as DiscordRpc::saveTemplates).
    template <int Kind>
    void saveBufferToFile() noexcept
    {
        static_assert(Kind >= 0 && Kind < chat_tools::kBufferKindCount);
        char path[512];
        if (!chat_tools::sidecarPathFor(hookContext, path, static_cast<chat_tools::BufferKind>(Kind)))
            return;
        const int fd = LinuxPlatformApi::open(path, O_WRONLY | O_CREAT | O_TRUNC, 0666);
        if (fd < 0)
            return;
        char sanitized[chat_tools::kBufferTextSize];
        const auto length = chat_tools::sanitizeInto(chat_tools::buffers[Kind].text, sanitized, sizeof(sanitized) - 1);
        sanitized[length] = '\n';
        static_cast<void>(LinuxPlatformApi::write(fd, sanitized, length + 1));
        LinuxPlatformApi::close(fd);
    }

    // Lazily pulls the sidecars into the menu buffers (game thread, once per buffer).
    void ensureBuffersLoaded() noexcept
    {
        for (int kind = 0; kind < chat_tools::kBufferKindCount; ++kind) {
            auto& state = chat_tools::buffers[kind];
            if (!state.loaded) {
                state.loaded = true;
                if (!readSidecar(hookContext, static_cast<chat_tools::BufferKind>(kind), state.text, sizeof(state.text)))
                    state.text[0] = '\0';
            }
        }
    }

    // Game thread ticker - CreateMove AND FrameStageNotify 6 (menu included). The parity gate
    // lets exactly one of the two per-frame callers drive the cadence; the subsystem states
    // below are namespace statics shared by both callers.
    void run() noexcept
    {
        CrashLogger::trace(0x310); // 0x310 entry / 0x311 exit (game thread)
        ensureBuffersLoaded();
        seedScriptPacks();

        if (chat_tools::callerParity.fetch_add(1, std::memory_order_relaxed) % 2 != 0) {
            CrashLogger::trace(0x311);
            return; // second caller of this frame - the first one already ticked the cadence
        }

        if (chat_tools::pendingNameApply.exchange(0, std::memory_order_acq_rel) != 0)
            applyFakeName();

        if (chat_tools::pendingCloneFragger.exchange(0, std::memory_order_acq_rel) != 0)
            cloneTopFragger();

        // the theater owns the name while it runs - spam/cycler would break the illusion
        const bool theaterActive = runBanTheater(chat_tools::pendingBanTheater.exchange(0, std::memory_order_acq_rel) != 0);

        runIntel();
        runPersonaPoll();

        if (!theaterActive) {
            runSpam();
            runNameCycle();
        }
        runHudColorCycle();
        runWheel();
        runLiveBadge();
        runFakeKick();
        CrashLogger::trace(0x311);
    }

    // Killstreak radio: escalates chatwheel voice lines on kill streaks. Wired from the
    // FireEventClientSide hook (EntryPoints) - the same dispatch Killsay hangs off.
    void onFireEventClientSide(cs2::IGameEvent* event) noexcept
    {
        if (!event)
            return;
        if (!GET_CONFIG_VAR(chat_vars::StreakRadioEnabled)) {
            chat_tools::streak = 0;
            return;
        }
        if (!game_events::is(event, "player_death"))
            return;
        CrashLogger::trace(0x320); // player_death reached the streak handler

        if (game_events::localPlayerIsAttacker(hookContext, event)) {
            ++chat_tools::streak;
            const char* line = nullptr;
            if (chat_tools::streak == 3)
                line = "Nice shot!";
            else if (chat_tools::streak == 5)
                line = "Excellent!";
            else if (chat_tools::streak == 8)
                line = "Everybody, get in here!";
            else if (chat_tools::streak == 12)
                line = "PEEK ME AGAIN I DARE YOU";
            if (line)
                sendWheel(line);
            return;
        }

        // our own death (or any death that is not our kill with us as victim) resets the streak
        if (game_events::localPlayerIsSlot(hookContext, game_events::entityForKey(event, "userid")))
            chat_tools::streak = 0;
    }

